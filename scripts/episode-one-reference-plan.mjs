export function referenceRemakeStoryboardIds(plan = REFERENCE_REMAKE_PLAN) {
  return plan
    .map((item) => Number(item.storyboardId))
    .filter((id, index, values) => id > 0 && values.indexOf(id) === index)
}

export function referenceRemakeDialogueItems(plan = REFERENCE_REMAKE_PLAN) {
  return plan.filter((item) => String(item.dialogueText || '').trim())
}

export function validateReferenceRemakePlan(plan = REFERENCE_REMAKE_PLAN) {
  const errors = []
  if (plan.length < 18 || plan.length > 30) {
    errors.push(`镜头数量必须在 18 到 30 之间，当前为 ${plan.length}`)
  }

  const seenKeys = new Set()
  const seenShotNumbers = new Set()
  for (const item of plan) {
    if (!item.key || seenKeys.has(item.key)) errors.push(`镜头 key 重复或为空：${item.key}`)
    seenKeys.add(item.key)
    if (!item.storyboardId && !item.storyboardKey) {
      errors.push(`镜头 ${item.shotNo} 缺少 storyboardId 或 storyboardKey`)
    }
    if (!item.shotNo || seenShotNumbers.has(item.shotNo)) {
      errors.push(`镜头编号重复或为空：${item.shotNo}`)
    }
    seenShotNumbers.add(item.shotNo)
    if (Number(item.durationSeconds) < 1) errors.push(`镜头 ${item.shotNo} 时长无效`)
    if (!String(item.visualPrompt || '').includes('竖屏 9:16')) {
      errors.push(`镜头 ${item.shotNo} 缺少竖屏构图约束`)
    }
  }

  const allText = plan.map((item) => item.dialogueText).join('\n')
  if (!allText.includes('六。别怕，小夏。')) errors.push('缺少“六。别怕，小夏。”')
  if (allText.includes('苏岚（广播）：五。') || allText.includes('苏岚（广播）：五')) {
    errors.push('不应生成苏岚广播“五”')
  }
  if (!allText.includes('苏岚（广播）：四。')) errors.push('缺少独立的广播“四”')

  const sixIndex = plan.findIndex((item) => item.dialogueText.includes('六。别怕，小夏。'))
  const fourIndex = plan.findIndex((item) => item.dialogueText.includes('苏岚（广播）：四。'))
  if (sixIndex < 0 || fourIndex < 0 || fourIndex <= sixIndex) {
    errors.push('倒数顺序不正确')
  }
  if (fourIndex >= 0 && plan[fourIndex + 1]?.dialogueText) {
    errors.push('广播“四”之后必须先有无对白反应/收束镜头')
  }

  return { valid: errors.length === 0, errors }
}

const validation = validateReferenceRemakePlan()
if (!validation.valid) {
  throw new Error(`参考片重制计划无效：${validation.errors.join('；')}`)
}
