export function buildPromptTemplateContext(scope = '') {
  const normalized = String(scope || '').trim().toLowerCase()
  const rules = SCOPED_CONTEXT[normalized]
  if (!rules) return ''
  return [
    `提示词模板技能：${PROMPT_TEMPLATE_SKILL_VERSION}`,
    `参考模板来源：${PROMPT_TEMPLATE_SOURCES[normalized]}`,
    ...rules,
  ].join('\n')
}

export function getPromptTemplateSkillSources() {
  return { ...PROMPT_TEMPLATE_SOURCES }
}
